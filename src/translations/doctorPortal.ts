export const doctorPortal = { en, ar };

export function formatDoctorText(template: string, ...values: (string | number)[]) {
    let index = 0;
    return template.replaceAll('{#}', () => String(values[index++] ?? ''));
}

export type DoctorPortalText = typeof en;

const stageKeys: (keyof DoctorPortalText)[] = [
    'stageReview', 'stageReady', 'stageDelivered', 'stageDesignShort', 'stageProductionShort',
    'stageReceived', 'stageDesign', 'stageProduction', 'stageCast', 'stageMilling', 'stageSintering',
    'stageFinishing', 'stageStaining', 'stageGlazing', 'stageQc', 'stagePackaging', 'stageShipping',
    'stageExternal', 'stageTryIn', 'stageMill', 'stageFinish', 'stageGlaze', 'stageFinalQc',
    'stagePack', 'stageShip', 'stageOutsource', 'stageRingPrep', 'stagePressing', 'stageRemake',
];

export function doctorStageLabel(value: string, t: DoctorPortalText) {
    if (t === ar) return value;
    const stages = value.split('، ');
    const translated = stages.map(stage => {
        const key = stageKeys.find(key => ar[key] === stage);
        return key ? t[key] : stage;
    });
    return translated.some((stage, index) => stage !== stages[index]) ? translated.join(', ') : value;
}

export function doctorPickupLabels(t: DoctorPortalText): Record<string, string> {
    return {
        requested: t.pickupRequested,
        scheduled: t.pickupScheduled,
        collected: t.pickupCollected,
        received: t.pickupReceived,
        cancelled: t.pickupCancelled,
    };
}

const textKeys = Object.keys(ar).filter((key): key is keyof DoctorPortalText => Object.hasOwn(en, key));

export function doctorMessage(t: DoctorPortalText, value: unknown, fallback: string) {
    const message = value instanceof Error ? value.message : value;
    const key = textKeys.find(key => ar[key] === message || en[key] === message);
    return key ? t[key] : fallback;
}
